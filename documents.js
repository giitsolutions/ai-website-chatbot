"use strict";

/*
    Uploaded documents (PDF, DOCX) as extra knowledge for one chatbot.

    - validateUpload()  checks name, size and the file's real format (signature).
    - extractDocument() turns the file into sections: PDF page by page (each section keeps
      its page number), DOCX with its headings and paragraphs (via the website extractor).
      Parsing runs in a separate reader process with a time and memory limit (documentWorker.js,
      started by documentSupervisor.js off the main thread);
      a .docx is first checked for how far it really expands when unzipped.
    - indexDocument()   chunks, embeds and stores the sections in Qdrant, tagged with the
      chatbot ID, sourceType "document" and the document ID, then removes that document's
      older sections (a re-index never duplicates; other documents and the website are
      never touched).
    - removeDocumentKnowledge() deletes the sections of exactly one document.

    Files are stored under data/uploads/<chatbot id>/<document id>.<ext>; the uploaded file
    name is only displayed, never used as a path.
*/

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const cheerio = require("cheerio");
const { Worker } = require("worker_threads");
const { QdrantClient } = require("@qdrant/js-client-rest");
const { extractSections, createChunks, createEmbeddings, cleanText } = require("./ingest");

const qdrant = new QdrantClient({ url: "http://localhost:6333" });
// QDRANT_COLLECTION (optional): another collection, e.g. an isolated one for tests.
const COLLECTION_NAME = process.env.QDRANT_COLLECTION || "website_content";
const EMBEDDING_MODEL = "nomic-embed-text";
const EMBEDDING_BATCH_SIZE = 16;

const SUPPORTED_TYPES = {
    ".pdf": { fileType: "pdf", label: "PDF" },
    ".docx": { fileType: "docx", label: "Word (.docx)" }
};
// Limits; optional .env overrides (whole numbers within the given range, otherwise the default).
function envWholeNumber(name, fallback, min, max) {
    const value = Number(process.env[name]);
    return Number.isInteger(value) && value >= min && value <= max ? value : fallback;
}
const MAX_DOCUMENT_BYTES = envWholeNumber("DOCUMENT_MAX_MB", 10, 1, 50) * 1024 * 1024;
const MAX_DOCUMENTS_PER_CHATBOT = envWholeNumber("DOCUMENTS_PER_CHATBOT", 50, 1, 500);
const MAX_PDF_PAGES = 500;
// A .docx is a ZIP file; this is the most its contents may expand to when opened.
const MAX_DOCX_UNCOMPRESSED_BYTES = 100 * 1024 * 1024;
// UPLOAD_DIR (optional): another folder for stored files, e.g. a temporary one for tests.
const UPLOAD_ROOT = process.env.UPLOAD_DIR ? path.resolve(process.env.UPLOAD_DIR) : path.join(__dirname, "data", "uploads");

function uploadError(message, status = 400) {
    const error = new Error(message);
    error.expose = true;
    error.status = status;
    return error;
}

// A display name: no folders, no control characters, at most 150 characters.
function cleanFilename(name) {
    const base = String(name || "").split(/[\\/]/).pop().replace(/[\u0000-\u001f\u007f]/g, "").trim();
    return base.slice(0, 150);
}

// Returns { filename, extension, fileType } or throws an error with a status for the visitor.
function validateUpload(filename, buffer) {
    const name = cleanFilename(filename);
    if (!name) throw uploadError("The file name is missing.");
    const extension = path.extname(name).toLowerCase();
    const type = SUPPORTED_TYPES[extension];
    if (!type) {
        throw uploadError(`"${name}" is not supported. Upload PDF (.pdf) or Word (.docx) files. Older .doc files are not supported: save them as .docx first.`, 415);
    }
    if (!Buffer.isBuffer(buffer) || buffer.length === 0) throw uploadError(`"${name}" is empty.`);
    if (buffer.length > MAX_DOCUMENT_BYTES) throw uploadError(`"${name}" is larger than ${MAX_DOCUMENT_BYTES / 1024 / 1024} MB.`, 413);

    // The content must really be that format, whatever the name says.
    if (type.fileType === "pdf" && !buffer.subarray(0, 1024).toString("latin1").includes("%PDF-")) {
        throw uploadError(`"${name}" is not a valid PDF file.`, 415);
    }
    if (type.fileType === "docx" && !(buffer.subarray(0, 4).equals(Buffer.from([0x50, 0x4b, 0x03, 0x04])) && buffer.includes("word/document.xml"))) {
        throw uploadError(`"${name}" is not a valid Word (.docx) file.`, 415);
    }
    return { filename: name, extension, fileType: type.fileType };
}

function storagePath(chatbotId, storageName) {
    // Both parts are generated by the server (UUIDs + a fixed extension).
    if (!/^[0-9a-f-]{36}$/i.test(chatbotId) || !/^[0-9a-f-]{36}\.(pdf|docx)$/i.test(storageName)) {
        throw new Error("Invalid storage name.");
    }
    return path.join(UPLOAD_ROOT, chatbotId, storageName);
}

async function saveFile(chatbotId, storageName, buffer) {
    const target = storagePath(chatbotId, storageName);
    await fs.promises.mkdir(path.dirname(target), { recursive: true });
    await fs.promises.writeFile(target, buffer, { flag: "wx" });
}

async function readFile(chatbotId, storageName) {
    return fs.promises.readFile(storagePath(chatbotId, storageName));
}

async function deleteFile(chatbotId, storageName) {
    await fs.promises.rm(storagePath(chatbotId, storageName), { force: true });
}

// The folder holding one chatbot's stored files (generated chatbot ID only, never a name from a request).
function chatbotFolder(chatbotId) {
    if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(chatbotId))) throw new Error("Invalid chatbot ID.");
    return path.join(UPLOAD_ROOT, String(chatbotId).toLowerCase());
}

// { files, bytes } stored for one chatbot (deletion preview).
async function chatbotFileStats(chatbotId) {
    const folder = chatbotFolder(chatbotId);
    let entries = [];
    try {
        entries = await fs.promises.readdir(folder, { withFileTypes: true });
    } catch (error) {
        if (error.code === "ENOENT") return { files: 0, bytes: 0 };
        throw error;
    }
    let bytes = 0;
    for (const entry of entries.filter(item => item.isFile())) bytes += (await fs.promises.stat(path.join(folder, entry.name))).size;
    return { files: entries.filter(item => item.isFile()).length, bytes };
}

// Removes one chatbot's folder of stored files; true when it no longer exists afterwards.
async function deleteChatbotFiles(chatbotId) {
    const folder = chatbotFolder(chatbotId);
    await fs.promises.rm(folder, { recursive: true, force: true });
    return !fs.existsSync(folder);
}

// ---- Extraction (in a reader child process, started by documentSupervisor.js) ----

// Parsing limits. A document that needs more time or memory is stopped and reported as
// failed with the reason; the server and chat answers are not affected.
const DOCUMENT_PARSE_TIMEOUT_MS = 120 * 1000;
const DOCUMENT_WORKER_MEMORY_MB = 512;
const PARSE_LIMITS = {
    maxDocxUncompressedBytes: MAX_DOCX_UNCOMPRESSED_BYTES,
    maxDocxEntries: 5000,
    maxPdfPages: MAX_PDF_PAGES
};

// The reader supervisor (documentSupervisor.js): one worker thread, started on first use, that
// starts a reader child process per document. Starting processes there keeps the ~0.6 s
// Windows process-creation pause off this (main) thread.
let supervisor = null;
let nextJobId = 1;
const pendingJobs = new Map();

function stopReader(pid) {
    if (!pid) return;
    try {
        process.kill(pid);
    } catch {
        // already gone
    }
}

function getSupervisor() {
    if (supervisor) return supervisor;
    const worker = new Worker(path.join(__dirname, "documentSupervisor.js"));
    worker.unref();
    worker.on("message", ({ id, started, readerPid, outcome }) => {
        const job = pendingJobs.get(id);
        if (!job) return;
        if (started) {
            job.readerPid = readerPid;
            if (job.onReaderStart) job.onReaderStart(readerPid);
            return;
        }
        job.done(outcome, readerPid);
    });
    // If the supervisor fails, its readers would no longer be timed or stopped: stop them here
    // (by process ID; a busy reader cannot be relied on to notice the lost connection itself).
    // Only this supervisor's jobs: a replaced supervisor that exits later must not fail jobs
    // already running on its successor.
    const fail = reason => {
        if (supervisor === worker) supervisor = null;
        for (const job of [...pendingJobs.values()].filter(pending => pending.worker === worker)) {
            stopReader(job.readerPid);
            job.done({ kind: "crash", detail: reason }, job.readerPid || null);
        }
    };
    worker.on("error", error => fail(`reader supervisor failed: ${error.message}`));
    worker.on("exit", code => fail(`reader supervisor stopped (exit code ${code})`));
    supervisor = worker;
    return worker;
}

// Runs one parse job in a new reader process. options (tests): timeoutMs, limits, memoryMb,
// onReaderStart(pid), backstopMs. Errors carry readerPid (the reader process ID) so tests can check the
// process is gone.
function runDocumentWorker(fileType, buffer, options = {}) {
    const timeoutMs = options.timeoutMs || DOCUMENT_PARSE_TIMEOUT_MS;
    const limits = { ...PARSE_LIMITS, ...(options.limits || {}) };
    const memoryMb = options.memoryMb || DOCUMENT_WORKER_MEMORY_MB;
    return new Promise((resolve, reject) => {
        const id = nextJobId++;
        const worker = getSupervisor();
        const done = (outcome, readerPid) => {
            if (!pendingJobs.has(id)) return;
            pendingJobs.delete(id);
            clearTimeout(backstop);
            if (outcome.kind === "ok") return resolve(outcome.result);
            let error;
            if (outcome.kind === "timeout") {
                error = uploadError(`The document took longer than ${Math.ceil(timeoutMs / 1000)} seconds to read and was stopped. Try a smaller or simpler file (for example, split it or save it again as a standard PDF).`, 422);
            } else if (outcome.kind === "memory") {
                error = uploadError("The document needs too much memory to read and was stopped. Try a smaller or simpler file.", 422);
            } else if (outcome.kind === "error") {
                error = outcome.error.expose ? uploadError(outcome.error.message, outcome.error.status || 422) : new Error(outcome.error.message);
            } else {
                error = new Error(`Document reader stopped unexpectedly (${outcome.detail}).`);
            }
            error.readerPid = readerPid;
            reject(error);
        };
        // Backstop if the supervisor itself stops answering: it is replaced for the next job.
        const backstop = setTimeout(() => {
            if (supervisor === worker) supervisor = null;
            const job = pendingJobs.get(id);
            stopReader(job && job.readerPid);
            worker.terminate().catch(() => {});
            done({ kind: "crash", detail: "the reader supervisor did not answer" }, job ? job.readerPid : null);
        }, (options.backstopMs || timeoutMs + 30000));
        pendingJobs.set(id, { done, worker, readerPid: null, onReaderStart: options.onReaderStart });
        const data = new Uint8Array(buffer); // a copy, handed over to the supervisor thread
        worker.postMessage({ id, fileType, data, limits, timeoutMs, memoryMb }, [data.buffer]);
    });
}

// A numbered heading inside a PDF page: a section number ("2", "2.1", "3.2.1", optionally with a
// final dot) followed by a capitalised title, at most 10 words, not ending like a sentence.
// Returns the section number, or null.
const NUMBERED_HEADING = /^(\d{1,2}(?:\.\d{1,2}){0,3})\.?\s+\p{Lu}/u;
function headingNumber(line) {
    const match = String(line).match(NUMBERED_HEADING);
    if (!match || line.split(/\s+/).length > 10 || /[.!?:;,]$/.test(line)) return null;
    return match[1];
}

// The sections of one PDF page: [{ heading, anchor, blocks, page }]. A short first line that looks
// like a title heads the page; numbered headings inside the page start new sections. Consecutive
// one-level numbers ("1. Open the form", "2. Check the amount") are a numbered list, not headings.
// Text before the first heading continues the previous page's section (continuedHeading), if any.
function pdfPageSections(pageNumber, lines, continuedHeading = null) {
    const numbers = lines.map(headingNumber);
    const level = number => (number ? number.split(".").length : 0);
    const inList = index => {
        const number = numbers[index];
        if (!number || level(number) > 1) return false;
        const previous = numbers[index - 1];
        const next = numbers[index + 1];
        return (level(previous) === 1 && Number(previous) === Number(number) - 1) ||
            (level(next) === 1 && Number(next) === Number(number) + 1);
    };
    const isHeading = index => Boolean(numbers[index]) && !inList(index);
    const first = lines[0] || "";
    const titleLike = !isHeading(0) && first.split(/\s+/).length <= 10 && !/[.!?:;,]$/.test(first);
    let start = 0;
    let heading = continuedHeading || `Page ${pageNumber}`;
    if (titleLike) {
        heading = first;
        start = 1;
    }
    const sections = [];
    let current = { heading, anchor: "", blocks: [], page: pageNumber };
    for (let index = start; index < lines.length; index++) {
        if (isHeading(index)) {
            if (current.blocks.length) sections.push(current);
            current = { heading: lines[index], anchor: "", blocks: [], page: pageNumber };
        } else {
            current.blocks.push(lines[index]);
        }
    }
    if (current.blocks.length) sections.push(current);
    // A page holding only headings (or a heading at its very end) still names its last heading,
    // so the next page's leading text is filed under it.
    return { sections, lastHeading: current.heading };
}

// Sections with their provenance: [{ heading, anchor, blocks, page? }].
async function extractDocument(buffer, fileType, filename, options = {}) {
    if (fileType === "pdf") {
        const { pageCount, pages: rawPages } = await runDocumentWorker("pdf", buffer, options);
        const pages = rawPages.map(page => ({ page: page.page, lines: page.lines.map(line => cleanText(line)).filter(Boolean) }));
        const sections = [];
        let lastHeading = null;
        for (const page of pages.filter(item => item.lines.length)) {
            const result = pdfPageSections(page.page, page.lines, lastHeading);
            sections.push(...result.sections);
            lastHeading = result.lastHeading;
        }
        return { pageCount, sections };
    }
    if (fileType === "docx") {
        const { html } = await runDocumentWorker("docx", buffer, options);
        const $ = cheerio.load(`<main>${html}</main>`);
        return { pageCount: null, sections: extractSections($, filename) };
    }
    throw uploadError("Unsupported document type.", 415);
}

// Chunks with provenance: [{ heading, chunk, page }]. Sections are never merged (unlike
// website price cards): in an authored document every heading and every PDF page is a
// place a citation must be able to name.
function documentChunks(extracted) {
    const chunks = [];
    for (const section of extracted.sections) {
        for (const part of createChunks([section], { mergeShortSections: false })) {
            chunks.push({ heading: part.heading, chunk: part.chunk, page: section.page || null });
        }
    }
    return chunks;
}

// ---- Storage in Qdrant ----

async function removeDocumentKnowledge(chatbotId, documentId, keepIds = []) {
    await qdrant.delete(COLLECTION_NAME, {
        wait: true,
        filter: {
            must: [
                { key: "chatbotId", match: { value: chatbotId } },
                { key: "documentId", match: { value: documentId } }
            ],
            ...(keepIds.length ? { must_not: [{ has_id: keepIds }] } : {})
        }
    });
}

async function countDocumentKnowledge(chatbotId, documentId) {
    const result = await qdrant.count(COLLECTION_NAME, {
        exact: true,
        filter: { must: [{ key: "chatbotId", match: { value: chatbotId } }, { key: "documentId", match: { value: documentId } }] }
    });
    return result.count || 0;
}

// Extracts, embeds and stores one document. Returns { pages, sections }; throws a
// customer-safe error (expose: true) when the document has no readable text.
// onStage(stage, detail) (optional) is told what is happening: "reading text", "creating
// embeddings" ({ done, total } sections), "saving".
async function indexDocument({ chatbotId, documentId, filename, fileType, buffer, onStage = () => {} }) {
    onStage("reading text");
    const extracted = await extractDocument(buffer, fileType, filename);
    const chunks = documentChunks(extracted);
    const words = chunks.reduce((sum, chunk) => sum + chunk.chunk.split(/\s+/).length, 0);
    if (!chunks.length || words < 5) {
        throw uploadError(fileType === "pdf"
            ? "No readable text found. The PDF may contain only scanned images; text recognition (OCR) is not supported."
            : "No readable text found in the document.", 422);
    }

    const texts = chunks.map(chunk => `
Document:
${filename}

Section:
${chunk.heading}${chunk.page ? ` (page ${chunk.page})` : ""}

Content:
${chunk.chunk}
`);
    const vectors = [];
    onStage("creating embeddings", { done: 0, total: texts.length });
    for (let start = 0; start < texts.length; start += EMBEDDING_BATCH_SIZE) {
        vectors.push(...await createEmbeddings(texts.slice(start, start + EMBEDDING_BATCH_SIZE)));
        onStage("creating embeddings", { done: vectors.length, total: texts.length });
    }

    const points = chunks.map((chunk, index) => ({
        id: crypto.randomUUID(),
        vector: vectors[index],
        payload: {
            chatbotId,
            sourceType: "document",
            documentId,
            filename,
            title: filename,
            heading: chunk.heading,
            anchor: "",
            chunk: chunk.chunk,
            page: chunk.page,
            pageType: "document",
            contentHash: crypto.createHash("sha256").update(`${EMBEDDING_MODEL}\n${texts[index]}`).digest("hex")
        }
    }));
    // New sections first, then this document's older ones: a failed upsert keeps the old knowledge.
    onStage("saving");
    await qdrant.upsert(COLLECTION_NAME, { wait: true, points });
    await removeDocumentKnowledge(chatbotId, documentId, points.map(point => point.id));
    return { pages: extracted.pageCount, sections: points.length };
}

